from sqlalchemy import Column, Integer, String, Boolean, DateTime, Text
from sqlalchemy.dialects.postgresql import JSONB
from datetime import datetime
from app.database import Base

class OnboardingOptiGlass(Base):
    __tablename__ = "onboarding_optiglass"
    id = Column(Integer, primary_key=True, autoincrement=True)
    id_interno = Column(String(50), unique=True, nullable=False)
    fecha_submit = Column(DateTime, default=datetime.utcnow, nullable=False)
    estado = Column(String(30), default="pending", nullable=False)
    status_changed_by = Column(String(100), nullable=True)
    status_changed_at = Column(DateTime, nullable=True)
    notas_internas_cjl = Column(Text, nullable=True)
    estado_seguimiento = Column(String(30), default="nuevo", nullable=True)
    fecha_ultimo_contacto = Column(DateTime, nullable=True)
    responsable_cjl = Column(String(50), nullable=True)
    archivos_adjuntos = Column(JSONB, nullable=True)
    version_documento = Column(String(20), default="v1.0", nullable=True)
    precios_json = Column(JSONB, nullable=True)
    email_cotizaciones = Column(String(120), nullable=True)
    telefono_cotizaciones = Column(String(40), nullable=True)
    sistema_cotizaciones = Column(String(50), nullable=True)
    tiempo_respuesta = Column(String(50), nullable=True)
    numero_principal_grupo = Column(String(40), nullable=True)
    garantias_json = Column(JSONB, nullable=True)
    texto_garantia_oficial = Column(Text, nullable=True)
    horario_lv = Column(String(60), nullable=True)
    horario_sabado = Column(String(60), nullable=True)
    horario_domingo = Column(String(60), nullable=True)
    servicio_movil = Column(Boolean, default=False)
    radio_millas = Column(String(50), nullable=True)
    direccion_taller = Column(Text, nullable=True)
    tiempo_parabrisas = Column(String(20), nullable=True)
    tiempo_lateral = Column(String(20), nullable=True)
    tiempo_trasero = Column(String(20), nullable=True)
    instaladores_disponibles = Column(String(20), nullable=True)
    ciudades_cobertura = Column(Text, nullable=True)
    zip_codes = Column(Text, nullable=True)
    zonas_no_trabajan = Column(Text, nullable=True)
    cobran_extra_movil = Column(Boolean, default=False)
    cuanto_extra = Column(String(50), nullable=True)
    promocion_actual = Column(Text, nullable=True)
    descuento_efectivo = Column(String(50), nullable=True)
    promo_adas = Column(String(100), nullable=True)
    promo_referidos = Column(String(100), nullable=True)
    otra_promo = Column(Text, nullable=True)
    metodos_pago_json = Column(JSONB, nullable=True)
    trabajan_aseguradoras = Column(Boolean, default=False)
    aseguradoras_json = Column(JSONB, nullable=True)
    manejan_deducibles = Column(String(100), nullable=True)
    como_cobran_claims = Column(Text, nullable=True)
    aceptan_seguro_cita = Column(Boolean, default=False)
    material_recibido = Column(Boolean, default=False)
    notas_material = Column(Text, nullable=True)
    acepta_terminos = Column(Boolean, default=False)
    autoriza_cliente = Column(Boolean, default=False)
    autoriza_cliente_nombre = Column(String(120), nullable=True)
    autoriza_cliente_sello = Column(String(200), nullable=True)
    autoriza_cliente_fecha = Column(DateTime, nullable=True)
    autoriza_cliente_ip = Column(String(60), nullable=True)
    autoriza_cjl = Column(Boolean, default=False)
    autoriza_cjl_nombre = Column(String(120), nullable=True)
    autoriza_cjl_sello = Column(String(200), nullable=True)
    autoriza_cjl_fecha = Column(DateTime, nullable=True)
